USE ROLE CAT07_LEARNER_RL;
USE WAREHOUSE CAT07_WH;
USE DATABASE RETAIL_ASSIST_DB;
USE SCHEMA RETAIL_ASSIST;

-- Upgrade the existing activity table instead of replacing it.
CREATE TABLE IF NOT EXISTS SUPPORT_ACTIVITY_LOG (
    ACTIVITY_ID VARCHAR(36) PRIMARY KEY,
    USER_ID VARCHAR(36),
    ACTIVITY_TYPE VARCHAR(60) NOT NULL,
    MODE VARCHAR(40),
    STATUS VARCHAR(20) NOT NULL DEFAULT 'SUCCESS',
    LATENCY_SECONDS FLOAT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Existing installations have USER_ID NOT NULL. Failed authentication attempts
-- can happen before a valid user is known, so the actor must be nullable.
ALTER TABLE SUPPORT_ACTIVITY_LOG ALTER COLUMN USER_ID DROP NOT NULL;

ALTER TABLE SUPPORT_ACTIVITY_LOG ADD COLUMN IF NOT EXISTS ACTOR_ROLE VARCHAR(20);
ALTER TABLE SUPPORT_ACTIVITY_LOG ADD COLUMN IF NOT EXISTS COMPONENT VARCHAR(80);
ALTER TABLE SUPPORT_ACTIVITY_LOG ADD COLUMN IF NOT EXISTS REQUEST_ID VARCHAR(36);
ALTER TABLE SUPPORT_ACTIVITY_LOG ADD COLUMN IF NOT EXISTS REASON VARCHAR(500);
ALTER TABLE SUPPORT_ACTIVITY_LOG ADD COLUMN IF NOT EXISTS DETAILS VARCHAR(2000);
ALTER TABLE SUPPORT_ACTIVITY_LOG ADD COLUMN IF NOT EXISTS ERROR_TYPE VARCHAR(200);
ALTER TABLE SUPPORT_ACTIVITY_LOG ADD COLUMN IF NOT EXISTS ERROR_MESSAGE VARCHAR(2000);
ALTER TABLE SUPPORT_ACTIVITY_LOG ADD COLUMN IF NOT EXISTS STARTED_AT TIMESTAMP_NTZ;
ALTER TABLE SUPPORT_ACTIVITY_LOG ADD COLUMN IF NOT EXISTS COMPLETED_AT TIMESTAMP_NTZ;

-- Useful indexes are intentionally omitted because Snowflake's standard tables
-- do not use traditional indexes. Queries below are written for Snowflake.

DESCRIBE TABLE SUPPORT_ACTIVITY_LOG;

SELECT
    STATUS,
    COUNT(*) AS EVENTS
FROM SUPPORT_ACTIVITY_LOG
GROUP BY STATUS
ORDER BY STATUS;

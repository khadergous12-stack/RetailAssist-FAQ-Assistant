USE ROLE CAT07_LEARNER_RL;
USE WAREHOUSE CAT07_WH;
USE DATABASE RETAIL_ASSIST_DB;
USE SCHEMA RETAIL_ASSIST;

CREATE TABLE IF NOT EXISTS SUPPORT_PASSWORD_RESET_REQUESTS (
    RESET_ID VARCHAR(36) PRIMARY KEY,
    USER_ID VARCHAR(36) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    REQUESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    COMPLETED_AT TIMESTAMP_NTZ
);

DESCRIBE TABLE SUPPORT_PASSWORD_RESET_REQUESTS;

SELECT *
FROM SUPPORT_PASSWORD_RESET_REQUESTS
ORDER BY REQUESTED_AT DESC;
